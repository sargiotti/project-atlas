// Regenerates src/time-zones.ts from the runtime's Intl data. Run: node packages/contract/scripts/gen-time-zones.mjs
// The worker test "every EVENT_TIME_ZONES entry passes the schema" proves the list matches workerd; re-run after a runtime upgrade.
import { writeFileSync } from "node:fs";
const zones = [...new Set([...Intl.supportedValuesOf("timeZone"), "UTC"])].sort();
const body = zones.map((z) => `  "${z}",`).join("\n");
const out = `// GENERATED by scripts/gen-time-zones.mjs. Do not edit by hand.
/** Canonical IANA time zone names accepted by the API (Worker/V8 canonical form), sorted. Used by the web dropdown. */
export const EVENT_TIME_ZONES: readonly string[] = [
${body}
];
`;
writeFileSync(new URL("../src/time-zones.ts", import.meta.url), out);
console.log(zones.length);
